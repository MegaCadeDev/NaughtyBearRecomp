#!/usr/bin/env python3
"""Generate tracing wrappers for every recompiled function in an address range.

Each recompiled function is called through a weak symbol (sub_XXXXXXXX), so a strong
definition here intercepts every call: it reports the call and then runs the original
(__imp__sub_XXXXXXXX). Used to map the statically linked Direct3D library at runtime.

usage: gen_trace_wrappers.py MAPPING OUT BEGIN END
"""
import pathlib
import re
import sys

mapping, out, begin, end = sys.argv[1], sys.argv[2], int(sys.argv[3], 16), int(sys.argv[4], 16)
functions = sorted({int(a, 16) for a, name in re.findall(r"\{ 0x([0-9A-F]+), (sub_[0-9A-F]+) \}", pathlib.Path(mapping).read_text())})
functions = [f for f in functions if begin <= f < end]

# Functions the runtime already wraps or replaces are left alone.
root = pathlib.Path(__file__).resolve().parent.parent
defined = set()
for source in (root / "src").rglob("*.cpp"):
    defined |= {int(a, 16) for a in re.findall(r"^PPC_FUNC\(sub_([0-9A-F]{8})\)", source.read_text(errors="replace"), re.M)}
functions = [f for f in functions if f not in defined]

lines = [
    "// Generated by tools/gen_trace_wrappers.py. Do not edit.",
    '#include "gpu/trace.h"',
    "",
]
for f in functions:
    lines.append(f'extern "C" PPC_FUNC(__imp__sub_{f:08X});')
    lines.append(f"PPC_FUNC(sub_{f:08X}) {{ nb::trace::Enter(0x{f:08X}, ctx); __imp__sub_{f:08X}(ctx, base); nb::trace::Leave(0x{f:08X}, ctx); }}")
pathlib.Path(out).write_text("\n".join(lines) + "\n")
print(f"{len(functions)} trace wrappers for 0x{begin:08X}-0x{end:08X}")
