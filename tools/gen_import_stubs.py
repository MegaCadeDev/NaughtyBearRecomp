#!/usr/bin/env python3
"""Generate a logging stub for every kernel/XAM import that has no implementation.

Reads the imports from generated/ppc/ppc_func_mapping.cpp, skips every import the
runtime implements (GUEST_FUNCTION_HOOK/GUEST_FUNCTION_STUB on __imp__<name> anywhere
under src/), and writes one NB_IMPORT_STUB per remaining import.
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
mapping = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "generated/ppc/ppc_func_mapping.cpp"
out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / "generated/import_stubs.cpp"

implemented = set()
for source in (root / "src").rglob("*.cpp"):
    implemented |= set(re.findall(r"GUEST_FUNCTION_(?:HOOK|STUB)\(\s*__imp__(\w+)", source.read_text(errors="replace")))

imports = set(re.findall(r"\{ 0x[0-9A-F]+, __imp__(\w+) \}", mapping.read_text()))
stubbed = sorted(imports - implemented)

lines = ["// Generated by tools/gen_import_stubs.py. Do not edit.", '#include "import_stub.h"', ""]
lines += [f"NB_IMPORT_STUB({name})" for name in stubbed]
out.write_text("\n".join(lines) + "\n")
print(f"{len(imports)} imports: {len(imports & implemented)} implemented, {len(stubbed)} stubbed")
