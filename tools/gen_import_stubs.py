#!/usr/bin/env python3
"""Generate a logging stub for every kernel/XAM import the recompiled code calls.

Reads generated/ppc/ppc_func_mapping.cpp and writes one NB_IMPORT_STUB per import.
Imports with a real implementation in src/kernel/ are skipped (listed in
src/kernel/implemented.txt), so stubs and implementations never collide.
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
mapping = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "generated/ppc/ppc_func_mapping.cpp"
out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / "generated/import_stubs.cpp"
implemented_file = root / "src/kernel/implemented.txt"

implemented = set()
if implemented_file.exists():
    implemented = {line.strip() for line in implemented_file.read_text().splitlines() if line.strip() and not line.startswith("#")}

imports = sorted(set(re.findall(r"\{ 0x[0-9A-F]+, __imp__(\w+) \}", mapping.read_text())) - implemented)

lines = [
    "// Generated by tools/gen_import_stubs.py. Do not edit.",
    '#include "import_stub.h"',
    "",
]
lines += [f"NB_IMPORT_STUB({name})" for name in imports]
out.write_text("\n".join(lines) + "\n")
print(f"{len(imports)} import stubs written to {out}")
